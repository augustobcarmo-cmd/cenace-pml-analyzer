"""Ubicación aproximada de los NodosP: subestaciones de OpenStreetMap y emparejamiento
por nombre, tensión y estado (sin Streamlit).

El CENACE no publica coordenadas de los NodosP. Se buscan subestaciones de OSM con
nombre parecido, en el mismo estado y, si se puede, con la misma tensión.
"""
